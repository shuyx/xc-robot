-- 
-- 1. 位置控制 (功能码0x03): 
--    - 写入寄存器40000(0x9C40)，参数范围0-100
--    - 0=完全张开，100=完全闭合
-- 
-- 2. 力度控制 (功能码0x05):
--    - 写入寄存器40001(0x9C41)，参数范围0-100  
--    - 0=最小力度，100=最大力度
-- 
-- 3. 位置读取 (功能码0x07):
--    - 读取寄存器40005(0x9C45)，返回当前位置0-100
-- 
-- 4. 力矩读取 (功能码0x08):
--    - 读取寄存器40006(0x9C46)，返回当前力矩0-100
-- 
-- 通讯参数: RS485, 115200波特率, 8N1, Modbus RTU协议
