-- 乐白夹爪实际可用的4个功能:
-- 1. 位置控制: 写入40000 (0x9C40) 
-- 2. 力度控制: 写入40001 (0x9C41)
-- 3. 位置读取: 读取40005 (0x9C45)
-- 4. 力矩读取: 读取40006 (0x9C46)

-- 指令模板数组定义 (参考AXLE_LUA_End_LeBai_Fixed.lua)
T1 = {0x01,0x10,0x9C,0x40,0x00,0x01,0x02,0x00,0x64}  -- 位置控制 (0x9C40)
T2 = {0x01,0x10,0x9C,0x41,0x00,0x01,0x02,0x00,0x32}  -- 力度控制 (0x9C41)
T3 = {0x01,0x03,0x9C,0x45,0x00,0x01}                -- 读取位置 (0x9C45)
T4 = {0x01,0x03,0x9C,0x46,0x00,0x01}                -- 读取力矩 (0x9C46)

-- 获取FR3系统发送的夹爪控制命令
Rcmd1,Rcmd2,Rcmd3,Rcmd4 = GetGripCmd()

-- 主控制流程 (完全参考AXLE_LUA_End_LeBai_Fixed.lua的简洁结构)
if(Rcmd1 == 1) then
    DelayMs(3)
    
    -- 更新所有指令模板中的设备地址
    T1[1] = Rcmd2
    T2[1] = Rcmd2
    T3[1] = Rcmd2
    T4[1] = Rcmd2
    
    -- 功能码3: 夹爪位置控制 (0x03) - 对应T1位置控制寄存器0x9C40
    if(Rcmd3 == 0x03) then
        T1[9] = Rcmd4  -- 设置位置参数(0-100)
        T1[10],T1[11] = CrcValue(T1[1],T1[2],T1[3],T1[4],T1[5],T1[6],T1[7],T1[8],T1[9])
        EndTxGripData(T1[1],T1[2],T1[3],T1[4],T1[5],T1[6],T1[7],T1[8],T1[9],T1[10],T1[11])
        DelayMs(10)
        Rxd1,Rxd2,Rxd3,Rxd4,Rxd5= EndRxGripData()
        GripStateBack(Rcmd4)  -- 返回设置的位置值
    end
    
    -- 功能码5: 夹爪力度控制 (0x05) - 对应T2力度控制寄存器0x9C41  
    if(Rcmd3 == 0x05) then
        T2[9] = Rcmd4  -- 设置力度参数(0-100)
        T2[10],T2[11] = CrcValue(T2[1],T2[2],T2[3],T2[4],T2[5],T2[6],T2[7],T2[8],T2[9])
        EndTxGripData(T2[1],T2[2],T2[3],T2[4],T2[5],T2[6],T2[7],T2[8],T2[9],T2[10],T2[11])
        DelayMs(10)
        Rxd1,Rxd2,Rxd3,Rxd4,Rxd5= EndRxGripData()
        GripStateBack(Rcmd4)  -- 返回设置的力度值
    end
    
    -- 功能码7: 读取夹爪位置状态 (0x07) - 对应T3读取位置寄存器0x9C45
    if(Rcmd3 == 0x07) then
        T3[7],T3[8] = CrcValue(T3[1],T3[2],T3[3],T3[4],T3[5],T3[6])
        EndTxGripData(T3[1],T3[2],T3[3],T3[4],T3[5],T3[6],T3[7],T3[8])
        DelayMs(10)
        a,Rxd1,Rxd2,Rxd3,Rxd4,Rxd5 = EndRxGripData()
        if ((a == 7) and (Rxd1 == Rcmd2) and (Rxd2 == 0x03) and (Rxd3 == 0x02)) then
            P = (Rxd4<<8)+Rxd5  -- 组合高低字节获取位置值
            GripStateBack(P)     -- 返回当前位置
        end
    end
    
    -- 功能码8: 读取夹爪力矩状态 (0x08) - 对应T4读取力矩寄存器0x9C46
    if (Rcmd3 == 0x08) then
        T4[7],T4[8] = CrcValue(T4[1],T4[2],T4[3],T4[4],T4[5],T4[6])
        EndTxGripData(T4[1],T4[2],T4[3],T4[4],T4[5],T4[6],T4[7],T4[8])
        DelayMs(10)
        a, Rxd1, Rxd2, Rxd3, Rxd4, Rxd5 = EndRxGripData()
        if ((a == 7) and (Rxd1 == Rcmd2) and (Rxd2 == 0x03) and (Rxd3 == 0x02)) then
            F = (Rxd4<<8)+Rxd5  -- 组合高低字节获取力矩值
            GripStateBack(F)     -- 返回当前力矩
        end
    end
end

